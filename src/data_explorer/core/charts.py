"""Altair charts (docs/architecture.md, "Charts").

Data is aggregated in pandas first and handed to Altair as plain records (at most 5,000 rows), so
the chart specification stays small and identical on the server and in the browser. Every chart is
360 pixels high and takes its width from Streamlit; its caption is stored as the Vega-Lite
description, which screen readers announce.
"""

from __future__ import annotations

from typing import Any, Literal

import altair as alt
import numpy as np
import pandas as pd

from data_explorer.core import json_safe
from data_explorer.core.profile import classify

Theme = Literal["dark", "light"]
Agg = Literal["count", "sum", "mean", "median"]
Freq = Literal["D", "W", "M"]
Method = Literal["pearson", "spearman"]

# --- kit palette: generated by tools/sync_kit.py from web/kit/echarts-theme.js; do not edit ---
PALETTE: dict[Theme, tuple[str, ...]] = {
    "dark": ("#C38102", "#058DB5", "#02AB70", "#AB6FE5", "#CA445C", "#77A304", "#028E7F", "#7A84EF"),
    "light": ("#B45309", "#0369A1", "#15803D", "#7E22CE", "#EB4960", "#3B6201", "#00948A", "#4338CA"),
}
SEQUENTIAL: dict[Theme, tuple[str, ...]] = {
    "dark": ("#6D4200", "#8B5502", "#AB6901", "#CB7E04", "#EC940D", "#FFB257"),
    "light": ("#F29B1D", "#D78602", "#BB7400", "#9F6202", "#845001", "#694002"),
}
DIVERGING: dict[Theme, tuple[str, ...]] = {
    "dark": ("#FFA9AF", "#EE6476", "#BC364E", "#3D3D3D", "#048073", "#0EB09E", "#57DDCA"),
    "light": ("#9D1135", "#D14A5F", "#FF7C8A", "#DEDEDE", "#36C3B0", "#039585", "#026359"),
}
# --- end of kit palette ---

DIVERGING_DOMAIN = tuple(round(-1 + step / 3, 6) for step in range(7))
SEQUENTIAL_DOMAIN = tuple(round(step / 5, 6) for step in range(6))
TEXT_COLOURS: dict[Theme, tuple[str, str]] = {"dark": ("#0B0F14", "#E6EDF3"), "light": ("#FFFFFF", "#14181D")}
TEXT_SWITCH: dict[Theme, float] = {"dark": 0.35, "light": 0.7}

HEIGHT = 360
MAX_INLINE_ROWS = 5_000
BINS_MIN, BINS_MAX = 5, 100
TOP_N_MIN, TOP_N_MAX = 5, 50
MAX_SERIES = 8
MAX_POINTS = 5_000
MAX_HEATMAP_COLUMNS = 20
HEATMAP_TEXT_MAX = 12
MIN_PAIRS = 10
MAX_BAR_TEXT_VALUES = 1_000
SEED = 20261029
MISSING_LABEL = "(missing)"
ALL_ROWS = "All rows"
MEASURE_AGGS = ("sum", "mean", "median")
FREQ_WORDS = {"D": "Daily", "W": "Weekly", "M": "Monthly"}
FREQ_AXIS = {"D": "Day", "W": "Week (starting Monday)", "M": "Month"}
FREQ_STEP = {"D": "D", "W": "W-MON", "M": "MS"}
POINT_MARKS_UP_TO = 60
MATRIX_CAPTION = (
    "Rows are grouped into up to 100 consecutive blocks; colour shows the share missing per block."
)


class ChartError(ValueError):
    """A chart that cannot be drawn from this data; the message says why."""


# --- helpers ---------------------------------------------------------------------------------


def _theme(theme: Theme) -> Theme:
    if theme not in PALETTE:
        raise ChartError(f"Unknown theme {theme!r}.")
    return theme


def _column(df: pd.DataFrame, column: str) -> pd.Series[Any]:
    if column not in df.columns:
        raise ChartError(f"Column `{column}` does not exist.")
    return df[column]


def _numeric(df: pd.DataFrame, column: str) -> pd.Series[Any]:
    series = _column(df, column)
    if classify(series) != "numeric":
        raise ChartError(f"`{column}` is not numeric.")
    return series.astype("float64")


def _labels(series: pd.Series[Any]) -> pd.Series[Any]:
    return series.astype("str").where(series.notna(), MISSING_LABEL)


def _groups(df: pd.DataFrame, column: str, what: str) -> pd.Series[Any]:
    labels = _labels(_column(df, column))
    distinct = int(labels.nunique())
    if distinct > MAX_SERIES:
        raise ChartError(f"`{column}` has {distinct} values; a chart shows at most 8 {what}.")
    return labels


def _check_agg(value: str | None, agg: str) -> None:
    if value is None and agg != "count":
        raise ChartError("Choose a measure column to use sum, mean or median.")
    if value is not None and agg not in MEASURE_AGGS:
        raise ChartError("A measure column needs the aggregation sum, mean or median.")


def _records(frame: pd.DataFrame) -> alt.InlineData:
    if len(frame) > MAX_INLINE_ROWS:
        raise ChartError(f"The chart would need {len(frame):,} data points; the limit is 5,000.")
    values = [
        {str(key): json_safe(item) for key, item in row.items()} for row in frame.to_dict(orient="records")
    ]
    return alt.InlineData(values=values)


def chart_caption(chart: alt.Chart | alt.LayerChart) -> str:
    """The caption shown under a chart (every builder stores it as the description)."""
    description: object = chart.description
    return description if isinstance(description, str) else ""


# --- data -------------------------------------------------------------------------------------


def histogram_data(df: pd.DataFrame, column: str, bins: int = 30) -> pd.DataFrame:
    values = _numeric(df, column).dropna().to_numpy(dtype="float64")
    if not BINS_MIN <= bins <= BINS_MAX:
        raise ChartError("The number of bins must be between 5 and 100.")
    if len(values) < 2:
        raise ChartError(f"`{column}` has fewer than 2 values to plot.")
    counts, edges = np.histogram(values, bins=bins)
    return pd.DataFrame({"bin_start": edges[:-1], "bin_end": edges[1:], "rows": counts.astype("int64")})


def bar_data(
    df: pd.DataFrame, category: str, value: str | None = None, agg: Agg = "count", top_n: int = 15
) -> pd.DataFrame:
    return _bar_rows(df, category, value, agg, top_n)[0]


def _bar_rows(
    df: pd.DataFrame, category: str, value: str | None, agg: Agg, top_n: int
) -> tuple[pd.DataFrame, int]:
    """The bars and the number of categories folded into the "Other" bar."""
    series = _column(df, category)
    kind = classify(series)
    if kind not in ("categorical", "boolean", "text"):
        raise ChartError(f"`{category}` is {kind}; bars need a categorical, boolean or text column.")
    if kind == "text" and int(series.nunique(dropna=True)) > MAX_BAR_TEXT_VALUES:
        raise ChartError(f"`{category}` has more than 1,000 distinct values, too many for a bar chart.")
    if not TOP_N_MIN <= top_n <= TOP_N_MAX:
        raise ChartError("Top N must be between 5 and 50.")
    _check_agg(value, agg)
    labels = _labels(series)
    measure: pd.Series[Any] | None = None
    if value is None:
        usable = len(labels)
        totals = labels.value_counts().astype("float64")
    else:
        measure = _numeric(df, value)
        usable = int(measure.notna().sum())
        totals = measure.groupby(labels, sort=False).agg(agg).dropna()
    if usable < 2:
        raise ChartError(f"`{category}` has fewer than 2 values to plot.")
    ordered = sorted(
        ((str(name), float(total)) for name, total in totals.items()), key=lambda item: (-item[1], item[0])
    )
    top, rest = ordered[:top_n], ordered[top_n:]
    if rest:
        names = {name for name, _ in rest}
        if measure is None:
            other = float(sum(total for _, total in rest))
        else:
            other = float(measure[labels.isin(names)].agg(agg))
        top.append((f"Other ({len(rest)} categories)", other))
    return pd.DataFrame(top, columns=["category", "value"]), len(rest)


def _period(dates: pd.Series[Any], freq: Freq) -> pd.Series[Any]:
    if freq == "D":
        periods = dates.dt.floor("D")
    elif freq == "W":
        periods = dates.dt.to_period("W-SUN").dt.start_time
    else:
        periods = dates.dt.to_period("M").dt.start_time
    shifted: pd.Series[Any] = periods.astype("datetime64[us]")
    return shifted


def line_data(
    df: pd.DataFrame,
    date_column: str,
    value: str | None = None,
    agg: Agg = "count",
    freq: Freq = "W",
    split: str | None = None,
) -> pd.DataFrame:
    dates = _column(df, date_column)
    if classify(dates) != "datetime":
        raise ChartError(f"`{date_column}` is not a date column.")
    if freq not in FREQ_WORDS:
        raise ChartError("The period must be D (day), W (week) or M (month).")
    _check_agg(value, agg)
    frame = pd.DataFrame({"period": _period(dates, freq)}, index=df.index)
    if value is not None:
        frame["value"] = _numeric(df, value)
    frame["series"] = ALL_ROWS if split is None else _groups(df, split, "series")
    frame = frame.dropna(subset=["period"])
    usable = len(frame) if value is None else int(frame["value"].notna().sum())
    if usable < 2:
        raise ChartError(f"`{date_column}` has fewer than 2 values to plot.")
    full = pd.date_range(frame["period"].min(), frame["period"].max(), freq=FREQ_STEP[freq]).as_unit("us")
    names = sorted(str(name) for name in frame["series"].unique())
    points = len(full) * len(names)
    if points > MAX_INLINE_ROWS:
        raise ChartError(f"The chart would have {points:,} points; choose a longer period or fewer series.")
    grouped = frame.groupby(["series", "period"])
    if value is None:
        result = grouped.size().astype("float64")
    elif agg == "sum":
        result = grouped["value"].sum(min_count=1)
    else:
        result = grouped["value"].agg(agg)
    index = pd.MultiIndex.from_product([names, full], names=["series", "period"])
    result = result.reindex(index)
    if value is None:
        result = result.fillna(0.0)
    return result.rename("value").reset_index()[["period", "series", "value"]]


def scatter_data(
    df: pd.DataFrame,
    x: str,
    y: str,
    color: str | None = None,
    max_points: int = MAX_POINTS,
    seed: int = SEED,
) -> tuple[pd.DataFrame, int]:
    if not 1 <= max_points <= MAX_POINTS:
        raise ChartError("The number of points must be between 1 and 5,000.")
    frame = pd.DataFrame({"x": _numeric(df, x), "y": _numeric(df, y)}, index=df.index)
    if color is not None:
        frame["group"] = _groups(df, color, "groups")
    frame = frame.dropna(subset=["x", "y"])
    total = len(frame)
    if total < 2:
        raise ChartError(f"Fewer than 2 rows have both a {x} and a {y} value.")
    if total > max_points:
        frame = frame.sample(n=max_points, random_state=seed).sort_index()
    return frame.reset_index(drop=True), total


def _numeric_columns(df: pd.DataFrame) -> list[str]:
    return [
        str(name) for position, name in enumerate(df.columns) if classify(df.iloc[:, position]) == "numeric"
    ]


def correlation_data(
    df: pd.DataFrame, method: Method = "pearson", max_columns: int = MAX_HEATMAP_COLUMNS
) -> pd.DataFrame:
    if method not in ("pearson", "spearman"):
        raise ChartError("The method must be pearson or spearman.")
    if not 2 <= max_columns <= MAX_HEATMAP_COLUMNS:
        raise ChartError("A heatmap shows between 2 and 20 columns.")
    numeric = _numeric_columns(df)
    if len(numeric) < 2:
        raise ChartError("A correlation heatmap needs at least 2 numeric columns.")
    chosen = numeric[:max_columns]
    matrix = df[chosen].astype("float64").corr(method=method, min_periods=MIN_PAIRS)
    rows = [(a, b, float(matrix[b][a])) for b in chosen for a in chosen]
    return pd.DataFrame(rows, columns=["a", "b", "r"])


# --- charts -----------------------------------------------------------------------------------


def histogram(df: pd.DataFrame, column: str, bins: int = 30, *, theme: Theme = "dark") -> alt.Chart:
    colours = PALETTE[_theme(theme)]
    data = histogram_data(df, column, bins)
    caption = f"{bins} equal-width bins over {int(data['rows'].sum()):,} non-missing values of {column}."
    drawn: alt.Chart = (
        alt.Chart(_records(data))
        .mark_bar(color=colours[0])
        .encode(
            x=alt.X("bin_start:Q", bin="binned", title=column),
            x2="bin_end",
            y=alt.Y("rows:Q", title="Rows"),
            tooltip=[
                alt.Tooltip("bin_start:Q", title="From"),
                alt.Tooltip("bin_end:Q", title="To"),
                alt.Tooltip("rows:Q", title="Rows", format=","),
            ],
        )
        .properties(height=HEIGHT, description=caption)
    )
    return drawn


def bar(
    df: pd.DataFrame,
    category: str,
    value: str | None = None,
    agg: Agg = "count",
    top_n: int = 15,
    *,
    theme: Theme = "dark",
) -> alt.Chart:
    colours = PALETTE[_theme(theme)]
    data, folded = _bar_rows(df, category, value, agg, top_n)
    title = "Rows" if value is None else f"{agg} of {value}"
    caption = ("Rows" if value is None else f"{agg.capitalize()} of {value}") + f" per {category}"
    if folded:
        caption += f"; the top {top_n} categories, the other {folded} as one bar"
    drawn: alt.Chart = (
        alt.Chart(_records(data))
        .mark_bar(color=colours[0])
        .encode(
            y=alt.Y("category:N", sort="-x", title=category),
            x=alt.X("value:Q", title=title),
            tooltip=[
                alt.Tooltip("category:N", title=category),
                alt.Tooltip("value:Q", title=title, format="," if value is None else ",.2f"),
            ],
        )
        .properties(height=HEIGHT, description=caption + ".")
    )
    return drawn


def line(
    df: pd.DataFrame,
    date_column: str,
    value: str | None = None,
    agg: Agg = "count",
    freq: Freq = "W",
    split: str | None = None,
    *,
    theme: Theme = "dark",
) -> alt.Chart:
    colours = PALETTE[_theme(theme)]
    data = line_data(df, date_column, value, agg, freq, split)
    periods = int(data["period"].nunique())
    title = "Rows" if value is None else f"{agg} of {value}"
    caption = f"{FREQ_WORDS[freq]} " + ("count of rows" if value is None else f"{agg} of {value}")
    if split is not None:
        caption += f" by {split}"
    if freq == "W":
        caption += "; weeks run Monday to Sunday"
    if value is not None and bool(data["value"].isna().any()):
        caption += "; periods without values are gaps"
    tooltip = [alt.Tooltip("period:T", title=FREQ_AXIS[freq], format="%Y-%m-%d")]
    if split is not None:
        tooltip.append(alt.Tooltip("series:N", title=split))
    tooltip.append(alt.Tooltip("value:Q", title=title, format="," if value is None else ",.2f"))
    encodings: dict[str, Any] = {
        "x": alt.X("period:T", title=FREQ_AXIS[freq]),
        "y": alt.Y("value:Q", title=title),
        "tooltip": tooltip,
    }
    if split is None:
        mark = alt.Chart(_records(data)).mark_line(
            point=periods <= POINT_MARKS_UP_TO, invalid=None, color=colours[0]
        )
    else:
        mark = alt.Chart(_records(data)).mark_line(point=periods <= POINT_MARKS_UP_TO, invalid=None)
        encodings["color"] = alt.Color("series:N", title=split, scale=alt.Scale(range=list(colours)))
    drawn: alt.Chart = mark.encode(**encodings).properties(height=HEIGHT, description=caption + ".")
    return drawn


def scatter(
    df: pd.DataFrame,
    x: str,
    y: str,
    color: str | None = None,
    max_points: int = MAX_POINTS,
    seed: int = SEED,
    *,
    theme: Theme = "dark",
) -> alt.Chart:
    colours = PALETTE[_theme(theme)]
    data, total = scatter_data(df, x, y, color, max_points, seed)
    caption = f"Sample of {len(data):,} of {total:,} points" if len(data) < total else f"{total:,} points"
    if len(df) > total:
        caption += f"; {len(df) - total:,} rows with a missing {x} or {y} are left out"
    tooltip = [alt.Tooltip("x:Q", title=x), alt.Tooltip("y:Q", title=y)]
    encodings: dict[str, Any] = {
        "x": alt.X("x:Q", title=x, scale=alt.Scale(zero=False)),
        "y": alt.Y("y:Q", title=y, scale=alt.Scale(zero=False)),
    }
    if color is None:
        mark = alt.Chart(_records(data)).mark_circle(size=30, opacity=0.6, color=colours[0])
    else:
        mark = alt.Chart(_records(data)).mark_circle(size=30, opacity=0.6)
        encodings["color"] = alt.Color("group:N", title=color, scale=alt.Scale(range=list(colours)))
        tooltip.append(alt.Tooltip("group:N", title=color))
    drawn: alt.Chart = mark.encode(tooltip=tooltip, **encodings).properties(
        height=HEIGHT, description=caption + "."
    )
    return drawn


def correlation_heatmap(
    df: pd.DataFrame,
    method: Method = "pearson",
    max_columns: int = MAX_HEATMAP_COLUMNS,
    *,
    theme: Theme = "dark",
) -> alt.Chart | alt.LayerChart:
    chosen_theme = _theme(theme)
    data = correlation_data(df, method, max_columns)
    order = list(dict.fromkeys(str(name) for name in data["a"]))
    available = len(_numeric_columns(df))
    caption = f"{method.capitalize()} correlation of {len(order)} numeric columns"
    if available > len(order):
        caption = (
            f"{method.capitalize()} correlation of the first {len(order)} of {available} numeric columns"
        )
    caption += "; pairs with fewer than 10 rows with both values are blank."
    base = alt.Chart(_records(data))
    x = alt.X("a:N", sort=order, title=None)
    y = alt.Y("b:N", sort=order, title=None)
    cells = base.mark_rect().encode(
        x=x,
        y=y,
        color=alt.Color(
            "r:Q",
            title="r",
            scale=alt.Scale(domain=list(DIVERGING_DOMAIN), range=list(DIVERGING[chosen_theme])),
        ),
        tooltip=[
            alt.Tooltip("a:N", title="Column"),
            alt.Tooltip("b:N", title="With"),
            alt.Tooltip("r:Q", format=".2f"),
        ],
    )
    if len(order) > HEATMAP_TEXT_MAX:
        flat: alt.Chart = cells.properties(height=HEIGHT, description=caption)
        return flat
    strong, weak = TEXT_COLOURS[chosen_theme]
    labels = (
        base.mark_text(fontSize=11)
        .encode(
            x=x,
            y=y,
            text=alt.Text("r:Q", format=".2f"),
            color=alt.when(alt.expr.abs(alt.datum.r) >= TEXT_SWITCH[chosen_theme])
            .then(alt.value(strong))
            .otherwise(alt.value(weak)),
        )
        .transform_filter("isValid(datum.r)")
    )
    return alt.layer(cells, labels).properties(height=HEIGHT, description=caption)


def missing_heatmap(matrix: pd.DataFrame, *, theme: Theme = "dark") -> alt.Chart:
    """The Quality page's matrix from ``quality.missing_matrix``."""
    chosen_theme = _theme(theme)
    needed = ["bin", "row_from", "row_to", "column", "missing_share"]
    if [name for name in needed if name not in matrix.columns]:
        raise ChartError("The missing-value matrix needs the columns " + ", ".join(needed) + ".")
    if matrix.empty:
        raise ChartError("The table has no rows to show.")
    order = list(dict.fromkeys(str(name) for name in matrix["column"]))
    drawn: alt.Chart = (
        alt.Chart(_records(matrix[needed]))
        .mark_rect()
        .encode(
            x=alt.X("column:N", sort=order, title=None, axis=alt.Axis(labelAngle=-45)),
            y=alt.Y("bin:O", title="Row block"),
            color=alt.Color(
                "missing_share:Q",
                title="Missing",
                scale=alt.Scale(domain=list(SEQUENTIAL_DOMAIN), range=list(SEQUENTIAL[chosen_theme])),
                legend=alt.Legend(format=".0%"),
            ),
            tooltip=[
                alt.Tooltip("column:N", title="Column"),
                alt.Tooltip("row_from:Q", title="First row", format=","),
                alt.Tooltip("row_to:Q", title="Last row", format=","),
                alt.Tooltip("missing_share:Q", title="Missing", format=".0%"),
            ],
        )
        .properties(height=HEIGHT, description=MATRIX_CAPTION)
    )
    return drawn
