"""Vendor portfolio-kit's dist/ at a pinned tag into web/kit/ and check it.

    uv run python tools/sync_kit.py                    copy dist/ at KIT_TAG from the local kit clone
    uv run python tools/sync_kit.py --check            compare web/kit/ with the kit at KIT_TAG
    uv run python tools/sync_kit.py --check --kit-dir .kit-src/dist
                                                       compare with a checked-out dist/ folder (CI)
    uv run python tools/sync_kit.py --palette-only     rewrite the palette block in core/charts.py
    uv run python tools/sync_kit.py --print-palette    show the colours read from echarts-theme.js

The copy reads `git archive` output of the local clone, so no network is involved. The kit clone
defaults to ../portfolio-kit next to this repository (override with --kit-repo or the
PORTFOLIO_KIT_REPO environment variable).
"""

from __future__ import annotations

import argparse
import ast
import hashlib
import io
import json
import os
import re
import shutil
import subprocess
import sys
import tarfile
from collections.abc import Mapping, Sequence
from pathlib import Path

KIT_TAG = "v0.1.0"
ROOT = Path(__file__).resolve().parents[1]
DEFAULT_KIT_REPO = ROOT.parent / "portfolio-kit"
KIT_DIR = ROOT / "web" / "kit"
CHARTS = ROOT / "src" / "data_explorer" / "core" / "charts.py"
MANIFEST = "MANIFEST.json"
LOCAL_FILES = frozenset({"VERSION"})
BLOCK_START = (
    "# --- kit palette: generated by tools/sync_kit.py from web/kit/echarts-theme.js; do not edit ---"
)
BLOCK_END = "# --- end of kit palette ---"
RAMPS = (("palette", "PALETTE", 8), ("sequential", "SEQUENTIAL", 6), ("diverging", "DIVERGING", 7))
THEMES = ("dark", "light")
HEX = re.compile(r"#[0-9A-Fa-f]{6}(?![0-9A-Fa-f])")

Palette = dict[str, dict[str, tuple[str, ...]]]


class KitError(RuntimeError):
    """A problem with the kit files; the message says what is wrong."""


def _sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def _check_relative(name: str) -> None:
    parts = name.split("/")
    if not name or name.startswith("/") or "\\" in name or ".." in parts or ":" in parts[0]:
        raise KitError(f"Refusing an unsafe path in the kit archive: {name!r}")


def read_archive(kit_repo: Path, tag: str) -> dict[str, bytes]:
    """Return the files under dist/ at ``tag`` as {path relative to dist/: bytes}."""
    if not (kit_repo / ".git").exists():
        raise KitError(
            f"No git clone of portfolio-kit at {kit_repo}; pass --kit-repo or set PORTFOLIO_KIT_REPO."
        )
    result = subprocess.run(
        ["git", "-c", "core.autocrlf=false", "-C", str(kit_repo), "archive", "--format=tar", tag, "dist"],
        capture_output=True,
        check=False,
    )
    if result.returncode != 0:
        raise KitError(f"git archive {tag} dist failed: {result.stderr.decode(errors='replace').strip()}")
    files: dict[str, bytes] = {}
    with tarfile.open(fileobj=io.BytesIO(result.stdout)) as archive:
        for member in archive.getmembers():
            if not member.isfile():
                continue
            relative = member.name.removeprefix("dist/")
            _check_relative(relative)
            extracted = archive.extractfile(member)
            if extracted is None:
                raise KitError(f"Cannot read {member.name} from the archive.")
            files[relative] = extracted.read()
    if not files:
        raise KitError(f"The archive of {tag} has no files under dist/.")
    return files


def read_dir(path: Path) -> dict[str, bytes]:
    """Return every file below ``path`` as {posix relative path: bytes}."""
    if not path.is_dir():
        raise KitError(f"{path} is not a folder.")
    return {
        item.relative_to(path).as_posix(): item.read_bytes()
        for item in sorted(path.rglob("*"))
        if item.is_file()
    }


def parse_manifest(data: bytes) -> dict[str, str]:
    """Return {path relative to dist/: lower-case SHA-256} from MANIFEST.json.

    Accepts a list of entries, an object with a "files" list, or an object mapping paths to a hash
    or to an entry; entries name the file as "file", "path" or "name"; a "dist/" prefix is removed.
    """
    try:
        payload = json.loads(data.decode("utf-8"))
    except (UnicodeDecodeError, json.JSONDecodeError) as exc:
        raise KitError(f"{MANIFEST} is not valid JSON: {exc}") from exc
    if isinstance(payload, dict) and "files" in payload:
        payload = payload["files"]
    entries: list[dict[str, object]] = []
    if isinstance(payload, dict):
        for name, value in payload.items():
            entry = dict(value) if isinstance(value, dict) else {"sha256": value}
            entry["file"] = name
            entries.append(entry)
    elif isinstance(payload, list):
        entries = [entry for entry in payload if isinstance(entry, dict)]
    result: dict[str, str] = {}
    for entry in entries:
        name = entry.get("file") or entry.get("path") or entry.get("name")
        digest = entry.get("sha256")
        if not isinstance(name, str) or not isinstance(digest, str):
            raise KitError(f"{MANIFEST} entry without a file name and a sha256: {entry!r}")
        result[name.removeprefix("dist/")] = digest.lower()
    if not result:
        raise KitError(f"{MANIFEST} lists no files.")
    return result


def verify(files: Mapping[str, bytes]) -> list[str]:
    """Compare a set of kit files with the MANIFEST.json among them."""
    if MANIFEST not in files:
        return [f"{MANIFEST} is missing"]
    manifest = parse_manifest(files[MANIFEST])
    problems: list[str] = []
    for name, digest in sorted(manifest.items()):
        if name == MANIFEST:
            continue
        if name not in files:
            problems.append(f"{name} is listed in {MANIFEST} but missing")
        elif _sha256(files[name]) != digest:
            problems.append(f"{name} does not match its SHA-256 in {MANIFEST}")
    for name in sorted(set(files) - set(manifest) - {MANIFEST} - LOCAL_FILES):
        problems.append(f"{name} is not listed in {MANIFEST}")
    return problems


def _declaration(source: str, name: str) -> str:
    """The initialiser of ``const|let|var <name> = ...`` up to its ``;`` at bracket depth 0."""
    match = re.search(rf"(?:export\s+)?(?:const|let|var)\s+{name}\s*=", source)
    if match is None:
        raise KitError(
            f"echarts-theme.js does not declare `{name}`; adjust parse_palette in tools/sync_kit.py."
        )
    depth = 0
    for index in range(match.end(), len(source)):
        char = source[index]
        if char in "([{":
            depth += 1
        elif char in ")]}":
            depth -= 1
        elif char == ";" and depth == 0:
            return source[match.end() : index]
    raise KitError(f"The declaration of `{name}` in echarts-theme.js does not end with `;`.")


def _theme_arrays(body: str, js_name: str) -> dict[str, str]:
    """Both arrays of a ramp: keyed ``{ dark: [...], light: [...] }`` or positional ``pair([dark], [light])``."""
    keyed = {
        theme: re.search(rf"[\"']?\b{theme}\b[\"']?\s*:\s*(?:Object\.freeze\(\s*)?\[(.*?)\]", body, re.S)
        for theme in THEMES
    }
    if all(keyed.values()):
        return {theme: match.group(1) for theme, match in keyed.items() if match is not None}
    arrays = re.findall(r"\[(.*?)\]", body, re.S)
    if len(arrays) != len(THEMES):
        raise KitError(
            f"`{js_name}` in echarts-theme.js has neither dark and light keys nor two arrays (dark, light)."
        )
    return dict(zip(THEMES, arrays, strict=True))


def parse_palette(source: str) -> Palette:
    """Read the palette, sequential and diverging colours for both themes from echarts-theme.js."""
    palette: Palette = {}
    for js_name, py_name, size in RAMPS:
        arrays = _theme_arrays(_declaration(source, js_name), js_name)
        themes: dict[str, tuple[str, ...]] = {}
        for theme in THEMES:
            colours = tuple(colour.upper() for colour in HEX.findall(arrays[theme]))
            if len(colours) != size:
                raise KitError(f"{py_name} {theme} has {len(colours)} colours, expected {size}.")
            themes[theme] = colours
        palette[py_name] = themes
    return palette


def render_block(palette: Palette) -> str:
    lines = [BLOCK_START]
    for _js_name, py_name, _size in RAMPS:
        lines.append(f"{py_name}: dict[Theme, tuple[str, ...]] = {{")
        for theme in THEMES:
            colours = ", ".join(f'"{colour}"' for colour in palette[py_name][theme])
            lines.append(f'    "{theme}": ({colours}),')
        lines.append("}")
    lines.append(BLOCK_END)
    return "\n".join(lines)


def _block_span(source: str) -> tuple[int, int]:
    start = source.find(BLOCK_START)
    end = source.find(BLOCK_END)
    if start < 0 or end < start:
        raise KitError("The palette block markers are missing in core/charts.py.")
    return start, end + len(BLOCK_END)


def replace_block(source: str, block: str) -> str:
    start, end = _block_span(source)
    return source[:start] + block + source[end:]


def read_block(source: str) -> Palette:
    start, end = _block_span(source)
    palette: Palette = {}
    for node in ast.parse(source[start:end]).body:
        if isinstance(node, ast.AnnAssign | ast.Assign):
            target = node.target if isinstance(node, ast.AnnAssign) else node.targets[0]
            if isinstance(target, ast.Name) and node.value is not None:
                value = ast.literal_eval(node.value)
                palette[target.id] = {str(key): tuple(colours) for key, colours in value.items()}
    return palette


def update_palette(kit_dir: Path = KIT_DIR, charts: Path = CHARTS) -> bool:
    """Rewrite the palette block in charts.py; return False when charts.py does not exist yet."""
    if not charts.exists():
        return False
    palette = parse_palette((kit_dir / "echarts-theme.js").read_text(encoding="utf-8"))
    source = charts.read_text(encoding="utf-8")
    updated = replace_block(source, render_block(palette))
    if updated != source:
        charts.write_text(updated, encoding="utf-8", newline="\n")
    return True


def sync(kit_repo: Path, tag: str, kit_dir: Path = KIT_DIR, charts: Path = CHARTS) -> int:
    """Replace kit_dir with dist/ at ``tag``; return the number of kit files copied."""
    files = read_archive(kit_repo, tag)
    problems = verify(files)
    if problems:
        raise KitError("The kit archive does not match its manifest: " + "; ".join(problems))
    if kit_dir.exists():
        shutil.rmtree(kit_dir)
    for name, data in files.items():
        target = kit_dir / name
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(data)
    (kit_dir / "VERSION").write_text(f"{tag}\n", encoding="utf-8", newline="\n")
    update_palette(kit_dir, charts)
    return len(files)


def check(
    tag: str, kit_repo: Path, source_dir: Path | None, kit_dir: Path = KIT_DIR, charts: Path = CHARTS
) -> list[str]:
    """Return every difference between kit_dir and the kit at ``tag`` (an empty list means current)."""
    problems: list[str] = []
    version_file = kit_dir / "VERSION"
    if not version_file.exists() or version_file.read_text(encoding="utf-8").strip() != tag:
        problems.append(f"web/kit/VERSION is not {tag}")
    vendored = {name: data for name, data in read_dir(kit_dir).items() if name not in LOCAL_FILES}
    source: dict[str, bytes] | None = None
    if source_dir is not None:
        source = read_dir(source_dir)
    elif (kit_repo / ".git").exists():
        source = read_archive(kit_repo, tag)
    if source is not None:
        problems.extend(f"kit source: {problem}" for problem in verify(source))
        for name in sorted(set(source) - set(vendored)):
            problems.append(f"{name} is missing in web/kit")
        for name in sorted(set(vendored) - set(source)):
            problems.append(f"{name} is in web/kit but not in the kit")
        for name in sorted(set(source) & set(vendored)):
            if _sha256(source[name]) != _sha256(vendored[name]):
                problems.append(f"{name} differs from the kit")
    problems.extend(verify(vendored))
    if charts.exists() and "echarts-theme.js" in vendored:
        expected = parse_palette(vendored["echarts-theme.js"].decode("utf-8"))
        if read_block(charts.read_text(encoding="utf-8")) != expected:
            problems.append(
                "the palette block in core/charts.py differs from web/kit/echarts-theme.js; run --palette-only"
            )
    return problems


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Vendor and check portfolio-kit in web/kit/.")
    parser.add_argument("--tag", default=KIT_TAG)
    parser.add_argument(
        "--kit-repo", type=Path, default=Path(os.environ.get("PORTFOLIO_KIT_REPO", DEFAULT_KIT_REPO))
    )
    parser.add_argument("--kit-dir", type=Path, help="a checked-out dist/ folder to compare with (CI)")
    group = parser.add_mutually_exclusive_group()
    group.add_argument("--check", action="store_true")
    group.add_argument("--palette-only", action="store_true")
    group.add_argument("--print-palette", action="store_true")
    args = parser.parse_args(argv)
    try:
        if args.check:
            problems = check(args.tag, args.kit_repo, args.kit_dir)
            if problems:
                for problem in problems:
                    print(f"sync_kit: {problem}", file=sys.stderr)
                return 1
            origin = args.kit_dir or (
                args.kit_repo if (args.kit_repo / ".git").exists() else "its own manifest"
            )
            print(f"sync_kit: web/kit matches portfolio-kit {args.tag} (compared with {origin})")
        elif args.print_palette:
            palette = parse_palette((KIT_DIR / "echarts-theme.js").read_text(encoding="utf-8"))
            for name, themes in palette.items():
                print(f"{name}: dark {' '.join(themes['dark'])} | light {' '.join(themes['light'])}")
        elif args.palette_only:
            if not update_palette():
                print("sync_kit: src/data_explorer/core/charts.py does not exist yet", file=sys.stderr)
                return 1
            print("sync_kit: palette block in src/data_explorer/core/charts.py is current")
        else:
            copied = sync(args.kit_repo, args.tag)
            print(f"sync_kit: copied {copied} files of portfolio-kit {args.tag} into web/kit")
            if not CHARTS.exists():
                print(
                    "sync_kit: core/charts.py does not exist yet; the palette block is written when it does"
                )
    except KitError as exc:
        print(f"sync_kit: {exc}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
